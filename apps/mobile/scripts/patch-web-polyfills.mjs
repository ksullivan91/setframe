#!/usr/bin/env node
/**
 * Makes `expo start --web` work against react-native 0.87.
 *
 * RN 0.87 dropped the `react-native/rn-get-polyfills` entrypoint, but
 * `@expo/cli` 57.0.17's *web* bundler path still does a bare
 * `require('react-native/rn-get-polyfills')` and catches only
 * MODULE_NOT_FOUND — not the ERR_PACKAGE_PATH_NOT_EXPORTED that a package
 * with an `exports` map actually throws. Metro then 500s on every bundle.
 *
 * Native is unaffected: `@expo/metro-config` reaches the same polyfills by
 * `path.join`ing a filesystem path, which ignores `exports`. So this only
 * ever touches the web preview, never an EAS build or a device bundle.
 *
 * Writes into node_modules, so it is undone by `npm ci` — re-run it after.
 * Delete this script once the Expo packages catch up (`npx expo install
 * --check` currently lists 17 packages behind).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const pkgPath = require.resolve('react-native/package.json');
const dir = pkgPath.slice(0, -'package.json'.length);
const shim = `${dir}rn-get-polyfills.js`;

if (!existsSync(shim)) {
  writeFileSync(
    shim,
    '// Generated by scripts/patch-web-polyfills.mjs — see that file.\n' +
      "module.exports = require('@react-native/js-polyfills');\n",
  );
}

const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
if (pkg.exports && !pkg.exports['./rn-get-polyfills']) {
  pkg.exports['./rn-get-polyfills'] = './rn-get-polyfills.js';
  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
}

console.log('react-native/rn-get-polyfills shim in place — expo web can bundle.');
